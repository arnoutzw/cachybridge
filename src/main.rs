fn portal_persistence(
    enabled: bool,
    token: Option<&str>,
) -> Result<portal_persistence::PortalPersistence, Box<dyn std::error::Error>> {
    if !enabled {
        return Ok(portal_persistence::PortalPersistence::disabled());
    }
    let token = token
        .map(portal_persistence::RestoreToken::new)
        .transpose()?;
    Ok(portal_persistence::PortalPersistence::persistent(token))
}

fn persist_returned_tokens(
    path: &std::path::Path,
    bridge_config: &mut config::BridgeConfig,
    peer_id: &str,
    updates: config::RestoreTokenUpdates,
) -> Result<(), Box<dyn std::error::Error>> {
    bridge_config.apply_restore_token_updates(peer_id, updates)?;
    config::save(path, bridge_config)?;
    Ok(())
}

fn run_seamless_client_config(
    config_override: Option<PathBuf>,
    peer_id: &str,
    peer_width: u32,
    peer_y: i32,
) -> Result<(), Box<dyn std::error::Error>> {
    if peer_width == 0 {
        return Err(
            io::Error::new(io::ErrorKind::InvalidInput, "peer width must be non-zero").into(),
        );
    }
    let (path, mut bridge_config, peer) = configured_peer(config_override, peer_id)?;
    let client_placement = horizontal_placement(peer.placement)?;
    // Pairing stores the complementary direction: client right means host is
    // on its right, so return through the client's right edge (and vice versa).
    let return_edge = match client_placement {
        config::RelativePlacement::Right => protocol::WireEdge::Right,
        config::RelativePlacement::Left => protocol::WireEdge::Left,
        config::RelativePlacement::Above | config::RelativePlacement::Below => unreachable!(),
    };

    eprintln!("starting configured RemoteDesktop and right InputCapture sessions; portal consent may be required");
    let mut injector = seamless::RemoteDesktopInjector::start_with_persistence(
        portal_persistence(peer.persistent_permissions, peer.remote_restore_token())?,
    )?;
    let returned_remote = injector
        .take_restore_token()
        .map(|token| token.into_secret());

    let mut return_watcher = match seamless::EdgeReturnWatcher::start_with_persistence(
        return_edge,
        peer_y,
        portal_persistence(peer.persistent_permissions, peer.capture_restore_token())?,
    ) {
        Ok(watcher) => watcher,
        Err(error) => {
            // The RemoteDesktop start has already consumed its restore token.
            // Persist its replacement/clear before returning this failure.
            if peer.persistent_permissions {
                persist_returned_tokens(
                    &path,
                    &mut bridge_config,
                    &peer.id,
                    config::RestoreTokenUpdates::remote(returned_remote),
                )?;
            }
            return Err(error);
        }
    };
    let returned_capture = return_watcher
        .take_restore_token()
        .map(|token| token.into_secret());
    if peer.persistent_permissions {
        // Both starts succeeded, so replace both single-use tokens together in
        // one 0600 atomic config rewrite before accepting network input.
        persist_returned_tokens(
            &path,
            &mut bridge_config,
            &peer.id,
            config::RestoreTokenUpdates::both(returned_capture, returned_remote),
        )?;
    }
    spawn_clipboard_client(peer.clone())?;
    let topology_changed = spawn_topology_control_listener(path, peer.clone())?;
    run_seamless_client_with_sessions(
        peer.client_endpoint,
        *peer.psk(),
        injector,
        return_watcher,
        Some(topology_changed),
    )
}

fn run_seamless_host(
    peer: SocketAddr,
    psk: [u8; 32],
    local_width: u32,
    local_height: u32,
    peer_width: u32,
    peer_height: u32,
    peer_y: i32,
) -> Result<(), Box<dyn std::error::Error>> {
    let peer_x = -i32::try_from(peer_width)
        .map_err(|_| io::Error::new(io::ErrorKind::InvalidInput, "peer width exceeds i32"))?;
    let local = handoff::Rect::new(0, 0, local_width, local_height).map_err(|error| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("invalid local layout: {error:?}"),
        )
    })?;
    let remote = handoff::Rect::new(peer_x, peer_y, peer_width, peer_height).map_err(|error| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("invalid peer layout: {error:?}"),
        )
    })?;
    eprintln!("starting InputCapture left-edge session; portal consent is required");
    let capture = seamless::InputCaptureAdapter::start_left(local.x)?;
    run_seamless_host_with_capture(peer, psk, local, remote, handoff::Edge::Left, capture)
}

fn run_seamless_host_with_capture(
    peer: SocketAddr,
    psk: [u8; 32],
    local: handoff::Rect,
    remote: handoff::Rect,
    edge: handoff::Edge,
    capture: seamless::InputCaptureAdapter,
) -> Result<(), Box<dyn std::error::Error>> {
    eprintln!("connecting seamless host to client at {peer}");
    // A client starts two portal sessions before it opens its input listener.
    // On a fresh GUI pairing Plasma may wait for the user to approve those
    // sessions, so the old eight-second retry window made a successful pairing
    // look broken. Keep the initial host session alive long enough for that
    // consent and listener handoff to complete.
    let stream = connect_seamless_peer(peer, Duration::from_secs(60))?;
    let connection = SecureConnection::connect(stream, Role::Host, &psk)?;
    connection.set_read_timeout(Some(Duration::from_millis(PEER_TIMEOUT_MS)))?;
    let controller = handoff::HandoffController::new(local, remote, edge);
    let mut host = seamless::SeamlessHost::new(controller, capture, connection);

    let forward_result: Result<(), Box<dyn std::error::Error>> = (|| loop {
        host.activate_once()?;
        if matches!(host.state(), handoff::HandoffState::RemoteActive { .. }) {
            while matches!(host.state(), handoff::HandoffState::RemoteActive { .. }) {
                host.forward_next(Duration::from_millis(HEARTBEAT_INTERVAL_MS))?;
            }
            eprintln!("peer returned to local host; edge barrier remains armed");
            continue;
        }
        eprintln!("peer rejected entry; edge barrier remains armed for another activation");
    })();

    // Cleanup first releases the exact portal activation, then makes a
    // best-effort encrypted release for the peer's pressed input ledger.
    let release_result = host.close();
    forward_result?;
    release_result?;
    Ok(())
}

/// Pairing saves the client configuration before its GUI starts the regular
/// listener. Allow that handoff to complete instead of failing the host on a
/// harmless, short-lived connection refusal.
fn connect_seamless_peer(peer: SocketAddr, timeout: Duration) -> io::Result<TcpStream> {
    let deadline = Instant::now() + timeout;
    loop {
        match TcpStream::connect(peer) {
            Ok(stream) => return Ok(stream),
            Err(error)
                if matches!(
                    error.kind(),
                    io::ErrorKind::ConnectionRefused
                        | io::ErrorKind::TimedOut
                        | io::ErrorKind::ConnectionAborted
                ) && Instant::now() < deadline =>
            {
                std::thread::sleep(Duration::from_millis(200));
            }
            Err(error) => return Err(error),
        }
    }
}

fn run_seamless_host_config(
    config_override: Option<PathBuf>,
    peer_id: &str,
    local_width: u32,
    local_height: u32,
    peer_width: u32,
    peer_height: u32,
    peer_y: i32,
) -> Result<(), Box<dyn std::error::Error>> {
    let (path, mut bridge_config, peer) = configured_peer(config_override, peer_id)?;
    let placement = horizontal_placement(peer.placement)?;
    let (peer_x, edge, capture_edge, capture_x) = match placement {
        config::RelativePlacement::Left => (
            -i32::try_from(peer_width).map_err(|_| {
                io::Error::new(io::ErrorKind::InvalidInput, "peer width exceeds i32")
            })?,
            handoff::Edge::Left,
            portal_spike::CaptureEdge::Left,
            0,
        ),
        config::RelativePlacement::Right => (
            i32::try_from(local_width).map_err(|_| {
                io::Error::new(io::ErrorKind::InvalidInput, "local width exceeds i32")
            })?,
            handoff::Edge::Right,
            portal_spike::CaptureEdge::Right,
            i32::try_from(local_width)
                .map_err(|_| {
                    io::Error::new(io::ErrorKind::InvalidInput, "local width exceeds i32")
                })?
                .saturating_sub(1),
        ),
        config::RelativePlacement::Above | config::RelativePlacement::Below => unreachable!(),
    };
    let local = handoff::Rect::new(0, 0, local_width, local_height).map_err(|error| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("invalid local layout: {error:?}"),
        )
    })?;
    let remote = handoff::Rect::new(peer_x, peer_y, peer_width, peer_height).map_err(|error| {
        io::Error::new(
            io::ErrorKind::InvalidInput,
            format!("invalid peer layout: {error:?}"),
        )
    })?;
    eprintln!("starting configured InputCapture edge session; portal consent may be required");
    let mut capture = seamless::InputCaptureAdapter::start_with_persistence(
        capture_edge,
        capture_x,
        portal_persistence(peer.persistent_permissions, peer.capture_restore_token())?,
    )?;
    if peer.persistent_permissions {
        persist_returned_tokens(
            &path,
            &mut bridge_config,
            &peer.id,
            config::RestoreTokenUpdates::capture(
                capture
                    .take_restore_token()
                    .map(|token| token.into_secret()),
            ),
        )?;
    }
    spawn_clipboard_host(peer.clone());
    run_seamless_host_with_capture(
        peer.client_endpoint,
        *peer.psk(),
        local,
        remote,
        edge,
        capture,
    )
}

fn run_host(
    peer: SocketAddr,
    psk: [u8; 32],
    devices: &[PathBuf],
    grab: bool,
    demo_events: Option<u32>,
    stop_after_reports: Option<u64>,
) -> Result<(), Box<dyn std::error::Error>> {
    eprintln!("connecting to client at {peer}");
    let stream = TcpStream::connect(peer)?;
    let mut connection = SecureConnection::connect(stream, Role::Host, &psk)?;

    if let Some(report_count) = demo_events {
        for _ in 0..report_count {
            for event in [
                WireInputEvent {
                    event_type: 2,
                    code: 0,
                    value: 3,
                },
                WireInputEvent {
                    event_type: 2,
                    code: 1,
                    value: 2,
                },
                WireInputEvent {
                    event_type: 0,
                    code: 0,
                    value: 0,
                },
            ] {
                connection.send(Message::Input(event))?;
            }
        }
        connection.send(Message::ReleaseAll)?;
        connection.send(Message::Goodbye)?;
        eprintln!("sent {report_count} synthetic pointer report(s)");
        return Ok(());
    }

    let (tx, rx) = sync_channel::<WireInputEvent>(INPUT_QUEUE_CAPACITY);
    let capture = start_capture(devices, grab, tx)?;
    eprintln!(
        "connected; forwarding input from {} device(s)",
        devices.len()
    );

    let mut pressed = BTreeSet::new();
    let mut forwarded_reports = 0_u64;
    let forwarding_result: Result<(), Box<dyn std::error::Error>> = loop {
        match rx.recv_timeout(Duration::from_millis(HEARTBEAT_INTERVAL_MS)) {
            Ok(event) => {
                update_pressed_keys(&mut pressed, event);
                if emergency_chord_active(&pressed, event) {
                    eprintln!("emergency release chord detected; returning input locally");
                    break Ok(());
                }
                if let Err(error) = connection.send(Message::Input(event)) {
                    break Err(Box::new(error));
                }
                if event.event_type == 0 && event.code == 0 && event.value == 0 {
                    forwarded_reports += 1;
                    if stop_after_reports == Some(forwarded_reports) {
                        eprintln!("forwarded requested {forwarded_reports} report(s)");
                        break Ok(());
                    }
                }
            }
            Err(std::sync::mpsc::RecvTimeoutError::Timeout) => {
                if let Err(error) = connection.send(Message::Heartbeat) {
                    break Err(Box::new(error));
                }
            }
            Err(std::sync::mpsc::RecvTimeoutError::Disconnected) => {
                break Err(Box::new(io::Error::new(
                    io::ErrorKind::BrokenPipe,
                    "all input capture workers stopped",
                )));
            }
        }
    };

    // A best-effort release prevents held controls on an orderly host shutdown.
    let graceful = forwarding_result.is_ok();
    let _ = connection.send(Message::ReleaseAll);
    if graceful {
        let _ = connection.send(Message::Goodbye);
    }
    let capture_result = capture.shutdown();
    forwarding_result?;
    capture_result?;
    Ok(())
}

fn update_pressed_keys(pressed: &mut BTreeSet<u16>, event: WireInputEvent) {
    if event.event_type != 1 {
        return;
    }
    match event.value {
        0 => {
            pressed.remove(&event.code);
        }
        1 => {
            pressed.insert(event.code);
        }
        _ => {}
    }
}

fn emergency_chord_active(pressed: &BTreeSet<u16>, event: WireInputEvent) -> bool {
    const KEY_ESC: u16 = 1;
    const CTRL: [u16; 2] = [29, 97];
    const SHIFT: [u16; 2] = [42, 54];
    const ALT: [u16; 2] = [56, 100];

    event.event_type == 1
        && event.code == KEY_ESC
        && event.value == 1
        && CTRL.iter().any(|code| pressed.contains(code))
        && SHIFT.iter().any(|code| pressed.contains(code))
        && ALT.iter().any(|code| pressed.contains(code))
}

fn run_client(
    listen: SocketAddr,
    psk: [u8; 32],
    dry_run: bool,
) -> Result<(), Box<dyn std::error::Error>> {
    let listener = TcpListener::bind(listen)?;
    eprintln!("waiting for host on {}", listener.local_addr()?);
    let (stream, peer) = listener.accept()?;
    eprintln!("host TCP connection from {peer}; authenticating");
    let mut connection = SecureConnection::connect(stream, Role::Client, &psk)?;
    connection.set_read_timeout(Some(Duration::from_millis(PEER_TIMEOUT_MS)))?;
    let mut sink = create_sink(dry_run)?;
    let mut event_count = 0_u64;
    eprintln!(
        "host authenticated; accepting input{}",
        if dry_run { " (dry run)" } else { "" }
    );

    let result: Result<(), Box<dyn std::error::Error>> = loop {
        match connection.receive() {
            Ok(Message::Input(event)) => {
                if let Err(error) = sink.inject(event) {
                    break Err(Box::new(error));
                }
                event_count += 1;
            }
            Ok(Message::Heartbeat) => {}
            Ok(Message::ReleaseAll | Message::HandoffRelease) => {
                if let Err(error) = sink.release_all() {
                    break Err(Box::new(error));
                }
            }
            Ok(Message::Enter { x, y }) => {
                // This acknowledgement only proves encrypted control-plane
                // wiring. Pointer placement is owned by the future portal/EIS
                // backend, so no local coordinates are applied here yet.
                eprintln!("accepted left-edge handoff request at ({x}, {y})");
                if let Err(error) = connection.send(Message::EnterAck) {
                    break Err(Box::new(error));
                }
            }
            Ok(Message::EnterAck | Message::EnterRejected) => {
                break Err(Box::new(io::Error::new(
                    io::ErrorKind::InvalidData,
                    "client received a handoff response without a local request",
                )));
            }
            Ok(Message::ExitRequest { .. }) => {
                break Err(Box::new(io::Error::new(
                    io::ErrorKind::InvalidData,
                    "manual client received a seamless-only exit request",
                )));
            }
            Ok(Message::PointerMotion { .. }) => {
                break Err(Box::new(io::Error::new(
                    io::ErrorKind::InvalidData,
                    "manual client received a seamless-only paired motion frame",
                )));
            }
            Ok(Message::Goodbye) => break Ok(()),
            Err(TransportError::Io(error))
                if matches!(
                    error.kind(),
                    io::ErrorKind::TimedOut | io::ErrorKind::WouldBlock
                ) =>
            {
                break Err(Box::new(io::Error::new(
                    io::ErrorKind::TimedOut,
                    "host heartbeat timed out",
                )));
            }
            Err(error) => break Err(Box::new(error) as Box<dyn std::error::Error>),
        }
    };

    // Safety invariant: every error path releases the virtual key/button state.
    let release_result = sink.release_all();
    result?;
    release_result?;
    eprintln!("session complete; received {event_count} input event(s)");
    Ok(())
}

