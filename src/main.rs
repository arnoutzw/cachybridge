#[allow(clippy::too_many_arguments)]
fn run_left_edge_demo(
    peer: SocketAddr,
    psk: [u8; 32],
    edge_y: i32,
    local_width: u32,
    local_height: u32,
    peer_x: i32,
    peer_y: i32,
    peer_width: u32,
    peer_height: u32,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut demo = handoff_demo::LeftEdgeDemo::side_by_side(
        local_width,
        local_height,
        peer_x,
        peer_y,
        peer_width,
        peer_height,
    )?;
    let enter = demo.left_barrier_activated(edge_y)?;
    if !matches!(demo.state(), handoff::HandoffState::EntryPending { .. }) {
        return Err(io::Error::other("left barrier did not enter a pending handoff state").into());
    }
    eprintln!("connecting to client at {peer} for simulated left-edge handoff");
    let stream = TcpStream::connect(peer)?;
    let mut connection = SecureConnection::connect(stream, Role::Host, &psk)?;
    connection.set_read_timeout(Some(Duration::from_millis(PEER_TIMEOUT_MS)))?;
    connection.send(enter)?;

    let result = match connection.receive()? {
        Message::EnterAck => {
            if demo.receive_peer_message(Message::EnterAck)? {
                eprintln!(
                    "left-edge handoff acknowledged; no portal/libei input backend is attached, releasing safely"
                );
                Ok(())
            } else {
                Err(io::Error::other("peer ACK did not activate the handoff"))
            }
        }
        Message::EnterRejected => {
            let _ = demo.receive_peer_message(Message::EnterRejected)?;
            Err(io::Error::new(
                io::ErrorKind::PermissionDenied,
                "peer rejected the left-edge handoff",
            ))
        }
        message => Err(io::Error::new(
            io::ErrorKind::InvalidData,
            format!("expected EnterAck or EnterRejected, received {message:?}"),
        )),
    };

    if let Some(release) = demo.release() {
        let _ = connection.send(release);
    }
    if result.is_ok() {
        let _ = connection.send(Message::Goodbye);
    }
    result.map_err(Into::into)
}

